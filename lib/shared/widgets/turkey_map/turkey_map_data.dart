  /// İlin id veya alternatif isimleri üzerinden ProvinceData bulur
  static ProvinceData? getProvince(String idOrName) {
    final clean = idOrName.toLowerCase().trim();
    if (clean == 'i-stanbul' || clean == 'istanbul') {
      return provinces['istanbul'];
    }
    if (clean == 'i-zmir' || clean == 'izmir') {
      return provinces['izmir'];
    }
    if (provinces.containsKey(clean)) {
      return provinces[clean];
    }
    for (final p in provinces.values) {
      if (p.name.toLowerCase() == clean) {
        return p;
      }
    }
    return null;
  }

  /// Belirli bir bölgeye ait illerin id listesi
  static List<String> getProvinceIdsInRegion(TurkeyRegion region) {
    return provinces.values
        .where((p) => p.region == region)
        .map((p) => p.id)
        .toList();
  }
